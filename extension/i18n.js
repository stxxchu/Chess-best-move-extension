  const NAMES = { en: 'English', pl: 'Polski' };

  function translator(lang) {
    const dict = STRINGS[lang] || STRINGS.en;
    return (key, ...args) => {
      let s = dict[key] !== undefined ? dict[key] : STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
      args.forEach((a, i) => { s = s.split(`{${i}}`).join(a); });
      return s;
    };
  }

  function pick(preferred, uiLanguage) {
    if (STRINGS[preferred]) return preferred;
    const base = String(uiLanguage || 'en').slice(0, 2).toLowerCase();
    return STRINGS[base] ? base : 'en';
  }

